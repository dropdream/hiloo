test('imágenes locales restringen lectura y actualizan su base al guardar como', async ({ application, editorPage: page }, testInfo) => {
  const path = testInfo.outputPath('original', 'nota.md')
  const copy = testInfo.outputPath('copia', 'nota.md')
  await fs.mkdir(dirname(path), { recursive: true })
  await fs.mkdir(dirname(copy), { recursive: true })
  await fs.writeFile(path, '![Local](pixel.png)\n')
  await fs.writeFile(testInfo.outputPath('original', 'pixel.png'), pixel)
  await fs.writeFile(testInfo.outputPath('fuera.png'), pixel)
  await fs.writeFile(testInfo.outputPath('original', 'falso.png'), '<script>active</script>')
  await chooseOpen(application, path)
  await page.getByRole('button', { name: 'Abrir', exact: true }).click()
  const img = page.getByRole('textbox', { name: 'Documento Markdown' }).locator('img:not(.ProseMirror-separator)')
  await expect.poll(() => img.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(1)
  const values = await page.evaluate(async () => {
    const { id } = await window.documents.current()
    return Promise.all([
      window.documents.imageSource('otro-documento', 'pixel.png'),
      window.documents.imageSource(id, '../fuera.png'),
      window.documents.imageSource(id, '%2e%2e/fuera.png'),
      window.documents.imageSource(id, 'file:///C:/secret.png'),
      window.documents.imageSource(id, 'falso.png'),
      window.documents.imageSource(id, 'pixel.png')
    ])
  })
  expect(values.slice(0, 5)).toEqual([null, null, null, null, null])
  expect(values[5]).toMatch(/^data:image\/png;base64,/)
  await chooseSave(application, copy)
  await page.getByRole('button', { name: 'Guardar como', exact: true }).click()
  await expect.poll(() => page.evaluate(async () => {
    const { id } = await window.documents.current()
    return window.documents.imageSource(id, 'pixel.png')
  })).toBeNull()
  // A stale data URL would display the previous folder's image after Save As.
  await expect(img).not.toHaveAttribute('src')
})
