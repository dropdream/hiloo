test('tabla se crea, modifica y guarda con filas y columnas', async ({ application, editorPage: page }, testInfo) => {
  const editor = page.getByRole('textbox', { name: 'Documento Markdown' })
  await page.getByRole('button', { name: 'Tabla', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Filas', { exact: true }).fill('3')
  await dialog.getByLabel('Columnas', { exact: true }).fill('2')
  await dialog.getByRole('button', { name: 'Insertar', exact: true }).click()
  await expect(editor.locator('table tr')).toHaveCount(3)
  await expect(editor.locator('table tr').first().locator('th')).toHaveCount(2)
  await editor.locator('th').first().click()
  await page.keyboard.insertText('Nombre')
  await editor.locator('td').first().click()
  await page.keyboard.insertText('Dato')
  await page.getByRole('button', { name: 'Tabla', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Insertar fila después', exact: true }).click()
  await expect(editor.locator('table tr')).toHaveCount(4)
  const path = testInfo.outputPath('tabla.md')
  await fs.mkdir(dirname(path), { recursive: true })
  await chooseSave(application, path)
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Guardado')
  expect(await fs.readFile(path, 'utf8')).toContain('Dato')
  await chooseOpen(application, path)
  await page.getByRole('button', { name: 'Abrir', exact: true }).click()
  await expect(editor.locator('table tr')).toHaveCount(4)
  const tableAction = async (name: string) => {
    await page.getByRole('button', { name: 'Tabla', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name, exact: true }).click()
  }
  await editor.locator('td').first().click()
  await tableAction('Centrar')
  await expect(editor.locator('th').first()).toHaveCSS('text-align', 'center')
  await tableAction('Insertar columna después')
  await expect(editor.locator('table tr').first().locator('th')).toHaveCount(3)
  await tableAction('Eliminar columna')
  await expect(editor.locator('table tr').first().locator('th')).toHaveCount(2)
  await editor.locator('th').first().click()
  await tableAction('Eliminar fila')
  await expect(editor.locator('table tr')).toHaveCount(3)
  await expect(editor.locator('th').first()).toHaveText('Dato')
  await tableAction('Eliminar tabla')
  await expect(editor.locator('table')).toHaveCount(0)
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await expect(editor.locator('table tr')).toHaveCount(3)
})

