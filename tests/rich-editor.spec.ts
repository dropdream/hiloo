test('GFM abre, visualiza imagen relativa, edita casillas y conserva estructura al guardar y reabrir', async ({ application, editorPage: page }, testInfo) => {
  const path = testInfo.outputPath('formatos.md')
  await fs.mkdir(dirname(path), { recursive: true })
  await fs.writeFile(testInfo.outputPath('pixel.png'), pixel)
  const source = '# Formatos\n\n| Nombre | Estado |\n| :--- | ---: |\n| Uno | ~~Antes~~ |\n\n- [ ] Pendiente\n- [x] Hecho\n\n![Pixel](pixel.png "Imagen local")\n\n[Referencia](https://example.com "Título")\n'
  await fs.writeFile(path, source)
  await chooseOpen(application, path)
  await page.getByRole('button', { name: 'Abrir', exact: true }).click()
  const editor = page.getByRole('textbox', { name: 'Documento Markdown' })
  await expect(editor.locator('table')).toHaveCount(1)
  await expect(editor.locator('del')).toHaveText('Antes')
  await expect(editor.getByRole('checkbox')).toHaveCount(2)
  await expect(editor.getByRole('checkbox').nth(0)).not.toBeChecked()
  await expect(editor.getByRole('checkbox').nth(1)).toBeChecked()
  await expect.poll(() => editor.locator('img:not(.ProseMirror-separator)').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(1)
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  expect(await fs.readFile(path, 'utf8')).toBe(source)
  await editor.getByRole('checkbox').nth(0).check()
  await expect(page.getByRole('status')).toHaveText('Cambios sin guardar')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Guardado')
  const saved = await fs.readFile(path, 'utf8')
  expect(markdownSignature(saved)).toBe(markdownSignature(source.replace('- [ ] Pendiente', '- [x] Pendiente')))
  await chooseOpen(application, path)
  await page.getByRole('button', { name: 'Abrir', exact: true }).click()
  await expect(editor.getByRole('checkbox').nth(0)).toBeChecked()
  await expect(editor.locator('table')).toContainText('Uno')
  await page.screenshot({ path: testInfo.outputPath('gfm-wide.png') })
  await (await application.browserWindow(page)).evaluate(win => win.setSize(420, 700))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('gfm-narrow.png') })
})

