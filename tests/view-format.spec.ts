  await expect(editor.locator('h1')).toHaveText('Última versión')
  await expect(editor.locator('strong')).toHaveText('Contenido recién editado')
  await editor.press('Control+End')
  await page.keyboard.insertText(' y revisión visual')
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  await expect(source).toHaveValue(/y revisión visual/)
  await source.press('Control+S')
  await expect(page.getByRole('status')).toHaveText('Guardado')
  expect(await fs.readFile(path, 'utf8')).toContain('y revisión visual')
  await chooseOpen(application, path)
  await page.getByRole('button', { name: 'Abrir', exact: true }).click()
  await page.getByRole('button', { name: 'Vista impresión', exact: true }).click()
  await expect(editor).toContainText('y revisión visual')
