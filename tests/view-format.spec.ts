test('Markdown no admitido conserva el borrador y permite corregir sin guardar una versión antigua', async ({ application, editorPage: page }, testInfo) => {
  const path = testInfo.outputPath('recuperado.md')
  await fs.mkdir(dirname(path), { recursive: true })
  await chooseSave(application, path)
  await page.getByRole('textbox', { name: 'Documento Markdown', exact: true }).fill('Versión anterior')
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  const source = page.getByRole('textbox', { name: 'Código Markdown', exact: true })
  const draft = '# Borrador pendiente\n\n<script>window.__unsafe = true</script>\n'
  await source.fill(draft)
  await page.getByRole('button', { name: 'Vista impresión', exact: true }).click()
  await expect(source).toBeVisible()
  await expect(source).toHaveValue(draft)
  await expect(page.getByRole('alert')).toBeVisible()
  await source.press('Control+S')
  await expect(page.getByRole('status')).toHaveText('Cambios sin guardar')
  await expect(fs.stat(path)).rejects.toMatchObject({ code: 'ENOENT' })
  await expect(source).toHaveValue(draft)
  expect(await page.evaluate(() => '__unsafe' in window)).toBe(false)
  await source.fill('# Borrador corregido\n\nTodo sigue aquí.\n')
  await source.press('Control+S')
  await expect(page.getByRole('status')).toHaveText('Guardado')
  expect(await fs.readFile(path, 'utf8')).toBe('# Borrador corregido\n\nTodo sigue aquí.\n')
  await page.getByRole('button', { name: 'Vista impresión', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Documento Markdown', exact: true }).locator('h1')).toHaveText('Borrador corregido')
})

