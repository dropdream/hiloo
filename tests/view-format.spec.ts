test('Día y Noche cambian interfaz, Markdown y ventana nativa manteniendo blanca la vista impresión', async ({ application, editorPage: page }, testInfo) => {
  const nativeWindow = await application.browserWindow(page)
  const rendered = page.getByRole('textbox', { name: 'Documento Markdown', exact: true })
  await rendered.fill('Documento con tema independiente')
  for (const [label, theme, nativeColor, rootColor, sourceColor] of [
    ['Día', 'day', '#ffffff', 'rgb(255, 255, 255)', 'rgb(32, 63, 93)'],
    ['Noche', 'night', '#183550', 'rgb(24, 53, 80)', 'rgb(237, 243, 248)']
  ]) {
    await page.getByRole('button', { name: label, exact: true }).click()
    await expect(page.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
    await expect(page.getByRole('main')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(rendered).toHaveCSS('color', 'rgb(23, 45, 64)')
    expect((await nativeWindow.evaluate(win => win.getBackgroundColor())).toLowerCase()).toBe(nativeColor)
    await page.getByRole('button', { name: 'Markdown', exact: true }).click()
    await expect(page.locator('body')).toHaveCSS('background-color', rootColor)
    await expect(page.getByRole('textbox', { name: 'Código Markdown', exact: true })).toHaveCSS('color', sourceColor)
    await page.screenshot({ path: testInfo.outputPath(`markdown-${theme}.png`) })
    await page.getByRole('button', { name: 'Vista impresión', exact: true }).click()
    await expect(rendered).toHaveText('Documento con tema independiente')
    await expect(page.getByRole('status')).toHaveText('Cambios sin guardar')
    await page.screenshot({ path: testInfo.outputPath(`impresion-${theme}.png`) })
  }
  const invalid = await page.evaluate(async () => {
    try { await window.appearance.setTheme('invalid' as 'day'); return 'accepted' }
    catch { return 'rejected' }
  })
  expect(invalid).toBe('rejected')
  await expect(page.getByRole('button', { name: 'Noche', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect((await nativeWindow.evaluate(win => win.getBackgroundColor())).toLowerCase()).toBe('#183550')
})

