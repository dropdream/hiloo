test('auditor: orígenes peligrosos se rechazan en formulario y lector local', async ({ application, editorPage: page }, info) => {
  for (const value of ['javascript:alert(1)', 'data:image/svg+xml,<svg/>', 'file:///C:/secret.png', '//example.com/a.png', 'C:\\secret.png', '/etc/passwd', '%2fetc/passwd']) expect(safeImage(value)).toBe(false)
  await button(page, 'Imagen').click()
  for (const value of ['javascript:alert(1)', 'data:image/png;base64,aaaa', 'file:///C:/secret.png']) {
    await page.getByRole('dialog').getByLabel('Origen', { exact: true }).fill(value)
    await page.getByRole('dialog').getByRole('button', { name: 'Insertar', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('alert')).toBeVisible()
    await expect(images(page)).toHaveCount(0)
  }
  await page.keyboard.press('Escape')
  await open(application, page, info.outputPath('safe', 'note.md'), 'Seguro\n')
  await fs.writeFile(info.outputPath('outside.png'), pixel)
  const results = await page.evaluate(async () => {
    const { id } = await window.documents.current()
    return Promise.all(['../outside.png', '%2e%2e/outside.png', '..%2foutside.png', 'file:///C:/secret.png', 'https://example.com/a.png'].map(source => window.documents.imageSource(id, source)))
  })
  expect(results).toEqual([null, null, null, null, 'https://example.com/a.png'])
})
