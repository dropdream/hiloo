const editor = (page: Page) => page.getByRole('textbox', { name: 'Documento Markdown' })
const images = (page: Page) => editor(page).locator('.document-image')
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const conversionErrors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ editorPage: page }) => {
  const errors: string[] = []
  conversionErrors.set(page, errors)
  page.on('console', message => {
    if (message.type() === 'error' && /milkdown|rangeerror|invalid content|parser|type of attribute|schema/i.test(message.text())) errors.push(message.text())
  })
})
test.afterEach(async ({ editorPage: page }) => { expect(conversionErrors.get(page)).toEqual([]) })
async function open(application: ElectronApplication, page: Page, path: string, source?: string) {
  if (source !== undefined) { await fs.mkdir(dirname(path), { recursive: true }); await fs.writeFile(path, source) }
  await chooseOpen(application, path)
  await button(page, 'Abrir').click()
  await expect(editor(page)).toBeVisible()
  await expect(editor(page)).toHaveAttribute('contenteditable', 'true')
}
async function save(application: ElectronApplication, page: Page, path?: string) {
  if (path) { await fs.mkdir(dirname(path), { recursive: true }); await chooseSave(application, path) }
  await button(page, 'Guardar').click()
  await expect(page.getByRole('status')).toHaveText('Guardado')
}
async function tableAction(page: Page, name: string) {
  await button(page, 'Tabla').click()
  await page.getByRole('dialog').getByRole('button', { name, exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function createTable(page: Page, rows: number, columns: number) {
  await button(page, 'Tabla').click()
  await page.getByRole('dialog').getByLabel('Filas', { exact: true }).fill(String(rows))
  await page.getByRole('dialog').getByLabel('Columnas', { exact: true }).fill(String(columns))
  await page.getByRole('dialog').getByRole('button', { name: 'Insertar', exact: true }).click()
}
async function imageDialog(page: Page, index = 0) {
  await images(page).nth(index).click()
  await button(page, 'Imagen').click()
  await expect(page.getByRole('dialog').getByRole('heading')).toHaveText('Editar imagen')
  return page.getByRole('dialog')
}

