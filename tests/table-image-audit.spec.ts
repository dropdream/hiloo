test('auditor: cabecera única, pipes y marcas sobreviven edición, guardado y reapertura', async ({ application, editorPage: page }, info) => {
  const path = info.outputPath('inline.md')
  const source = '| **Fuerte** | *Énfasis* |\n| :--- | ---: |\n| `a\\|b` | ~~viejo~~ y [sitio](https://example.com) |\n\nFinal\n'
  await open(application, page, path, source)
  await expect(editor(page).locator('code')).toHaveText('a|b')
  await editor(page).locator('td').first().click()
  await tableAction(page, 'Insertar fila después')
  await tableAction(page, 'Eliminar fila')
  await save(application, page)
  expect(markdownSignature(await fs.readFile(path, 'utf8'))).toBe(markdownSignature(source))
  await open(application, page, path)
  await expect(editor(page).locator('strong')).toHaveText('Fuerte')
  await expect(editor(page).locator('em')).toHaveText('Énfasis')
  await expect(editor(page).locator('del')).toHaveText('viejo')
  await editor(page).locator('td').first().click()
  await tableAction(page, 'Eliminar fila')
  await expect(editor(page).locator('tr')).toHaveCount(1)
  await save(application, page)
  await open(application, page, path)
  await expect(editor(page).locator('tr')).toHaveCount(1)
})

test('auditor: filas y columnas antes/después conservan extremos y encabezado', async ({ application, editorPage: page }, info) => {
  await open(application, page, info.outputPath('edges.md'), '| H1 | H2 |\n| --- | --- |\n| A1 | A2 |\n| B1 | B2 |\n')
  const rows = editor(page).locator('tr')
  await editor(page).locator('th').first().click()
  await tableAction(page, 'Insertar fila antes')
  await expect(rows).toHaveCount(4)
  await expect(rows.nth(1)).toContainText('H1')
  await expect(rows.first().locator('th')).toHaveCount(2)
  await tableAction(page, 'Eliminar fila')
  await expect(rows.first()).toContainText('H1')
  await rows.last().locator('td').last().click()
  await tableAction(page, 'Insertar fila después')
  await expect(rows).toHaveCount(4)
  await tableAction(page, 'Eliminar fila')
  await expect(rows.last()).toContainText('B2')
  await editor(page).locator('th').first().click()
  await tableAction(page, 'Insertar columna antes')
  await expect(rows.first().locator('th')).toHaveCount(3)
  await expect(rows.first().locator('th').nth(1)).toHaveText('H1')
  await tableAction(page, 'Eliminar columna')
  await rows.last().locator('td').last().click()
  await tableAction(page, 'Insertar columna después')
  await expect(rows.last().locator('td')).toHaveCount(3)
  await tableAction(page, 'Eliminar columna')
  await expect(rows.last().locator('td')).toHaveText(['B1', 'B2'])
  await button(page, 'Deshacer').click()
  await expect(rows.last().locator('td')).toHaveCount(3)
  await button(page, 'Rehacer').click()
  await expect(rows.last().locator('td')).toHaveText(['B1', 'B2'])
})

test('auditor: alineación completa persiste y última columna se elimina con historial', async ({ application, editorPage: page }, info) => {
  const path = info.outputPath('alignment.md')
  await open(application, page, path, '| A | B | C |\n| --- | --- | --- |\n| 1 | 2 | 3 |\n')
  for (const [column, name, value] of [[0, 'Alinear a la izquierda', 'left'], [1, 'Centrar', 'center'], [2, 'Alinear a la derecha', 'right']] as const) {
    await editor(page).locator('td').nth(column).click()
    await tableAction(page, name)
    await expect(editor(page).locator('th').nth(column)).toHaveCSS('text-align', value)
    await expect(editor(page).locator('td').nth(column)).toHaveCSS('text-align', value)
  }
  await save(application, page)
  await open(application, page, path)
  for (const [column, value] of ['left', 'center', 'right'].entries()) await expect(editor(page).locator('td').nth(column)).toHaveCSS('text-align', value)
  await editor(page).locator('th').first().click()
  for (let index = 0; index < 3; index++) await tableAction(page, 'Eliminar columna')
  await expect(editor(page).locator('table')).toHaveCount(0)
  await button(page, 'Deshacer').click()
  await expect(editor(page).locator('th')).toHaveText('C')
  await button(page, 'Rehacer').click()
  await expect(editor(page).locator('table')).toHaveCount(0)
})

